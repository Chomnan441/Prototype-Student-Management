import type { Student, StudentStatus } from "../types";

function student(
  sequence: number,
  firstName: string,
  lastName: string,
  nickname: string,
  parentName: string,
  phone: string,
  registrationDate: string,
  status: StudentStatus,
  note: string,
): Student {
  return {
    id: `STU-${String(sequence).padStart(4, "0")}`,
    firstName,
    lastName,
    nickname,
    parentName,
    phone,
    registrationDate,
    status,
    note,
    createdAt: `${registrationDate}T02:00:00.000Z`,
  };
}

